import { expect, test } from '@playwright/test';

test('manages plugin and skill views while preserving the conversation draft', async ({ page }, testInfo) => {
  await page.goto('/');
  const input = page.getByRole('textbox', { name: '剪辑需求' });
  await input.fill('检查本地项目配置');
  const inputNode = await input.elementHandle();
  await page.getByRole('button', { name: '插件和技能', exact: true }).click();
  await expect(page.getByRole('main', { name: '插件管理' })).toBeVisible();
  await expect(page.getByRole('tab', { name: '公开', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: '安装 语义视频剪辑', exact: true }).click();
  await expect(page.getByRole('button', { name: '语义视频剪辑操作', exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('plugins.png') });
  await page.getByRole('tab', { name: '个人', exact: true }).click();
  await expect(page.getByRole('main', { name: '插件管理' }).getByRole('button', { name: '查看 语义视频剪辑' })).toHaveCount(0);
  await page.getByRole('tab', { name: '公开', exact: true }).click();
  await page.getByRole('button', { name: '语义视频剪辑操作', exact: true }).click();
  await expect(page.getByRole('menuitem', { name: '立即试用' })).toBeEnabled();
  await page.screenshot({ path: testInfo.outputPath('plugin-row-menu.png') });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('menu')).not.toBeVisible();
  await page.getByRole('button', { name: '语义视频剪辑操作', exact: true }).click();
  await page.getByRole('menuitem', { name: '管理', exact: true }).click();
  await expect(page.getByRole('switch', { name: '启用 语义视频剪辑' })).toBeChecked();
  await page.getByRole('switch', { name: '启用 语义视频剪辑' }).uncheck();
  await expect(page.getByRole('button', { name: '使用', exact: true })).toBeDisabled();
  await page.getByRole('switch', { name: '启用 语义视频剪辑' }).check();
  await page.getByRole('button', { name: '技能', exact: true }).click();
  await expect(page.getByRole('button', { name: '查看 semantic-editing' })).toBeVisible();
  await page.getByRole('button', { name: '安装 local-file-review' }).click();
  await page.getByRole('switch', { name: '启用 local-file-review' }).uncheck();
  await expect(page.getByRole('switch', { name: '启用 local-file-review' })).not.toBeChecked();
  await page.getByRole('textbox', { name: '搜索技能' }).fill('不存在');
  await expect(page.getByText('没有匹配结果')).toBeVisible();
  await page.getByRole('textbox', { name: '搜索技能' }).fill('');
  await page.screenshot({ path: testInfo.outputPath('skills.png') });
  await page.getByRole('button', { name: '查看 local-file-review' }).click();
  const skillDialog = page.getByRole('dialog', { name: 'local-file-review技能详情' });
  await expect(skillDialog.getByLabel('技能正文')).toContainText('浏览器预览技能正文');
  await skillDialog.getByRole('button', { name: '技能操作' }).click();
  await skillDialog.getByRole('menuitem', { name: '卸载', exact: true }).click();
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await expect(skillDialog).toBeVisible();
  await skillDialog.getByRole('button', { name: '技能操作' }).click();
  await skillDialog.getByRole('menuitem', { name: '卸载', exact: true }).click();
  await page.getByRole('button', { name: '确认卸载' }).click();
  await expect(page.getByRole('button', { name: '安装 local-file-review' })).toBeVisible();
  await page.getByRole('button', { name: '添加技能' }).click();
  await expect(page.getByRole('alert')).toContainText('桌面应用');
  await page.getByRole('button', { name: '对话', exact: true }).click();
  await expect(input).toHaveValue('检查本地项目配置');
  expect(await input.evaluate((element, original) => element === original, inputNode)).toBe(true);
  await page.getByRole('button', { name: '插件和技能', exact: true }).click();
  await page.getByRole('button', { name: '插件', exact: true }).click();
  await page.getByRole('button', { name: '语义视频剪辑操作', exact: true }).click();
  await page.getByRole('menuitem', { name: '立即试用' }).click();
  await expect(input).toHaveValue('$semantic-editing\n检查本地项目配置');
  await expect(page.locator('.user-message')).toHaveCount(0);
});

test('keeps extension controls and long details contained at 400px', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 400, height: 740 });
  await page.goto('/');
  await page.getByRole('button', { name: '插件和技能', exact: true }).click();
  await page.getByRole('button', { name: '查看 语义视频剪辑' }).click();
  await expect(page.getByRole('region', { name: '信息' })).toContainText('Agent Desktop');
  await expect(page.locator('.extension-detail')).not.toContainText('事件钩子');
  await page.getByText('插件清单', { exact: true }).click();
  await expect(page.locator('.extension-detail pre')).toContainText('video-editing');
  expect(await page.locator('.extensions-page').evaluate(element => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(1);
  for (const button of await page.locator('.extensions-page button').all()) {
    const bounds = (await button.boundingBox())!;
    expect(bounds.x).toBeGreaterThanOrEqual(116);
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(400);
  }
  await page.screenshot({ path: testInfo.outputPath('plugin-narrow.png') });
});

test('uses plugin trial prompts and confirms uninstall through the list menu', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.getByRole('textbox', { name: '剪辑需求' }).fill('保留素材要求');
  await page.getByRole('button', { name: '插件和技能', exact: true }).click();
  await page.getByRole('button', { name: '安装 语义视频剪辑' }).click();
  await page.getByRole('button', { name: '查看 语义视频剪辑', exact: true }).click();
  await page.getByRole('region', { name: '建议指令' }).getByRole('button', { name: /短剧剪辑/ }).click();
  await expect(page.getByRole('textbox', { name: '剪辑需求' })).toHaveValue('使用 $short-drama-editing 整理短剧素材，先确认画幅、时长与剧情重点。\n保留素材要求');
  await expect(page.locator('.user-message')).toHaveCount(0);
  await page.getByRole('button', { name: '插件和技能', exact: true }).click();
  await page.getByRole('button', { name: '查看 语义视频剪辑', exact: true }).click();
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; });
  await page.getByRole('button', { name: '插件操作' }).click();
  await page.screenshot({ path: testInfo.outputPath('plugin-detail-dark.png') });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('menu')).not.toBeVisible();
  await page.getByRole('button', { name: '返回插件', exact: true }).click();
  await page.getByRole('button', { name: '语义视频剪辑操作', exact: true }).click();
  await page.getByRole('menuitem', { name: '卸载' }).click();
  await page.getByRole('button', { name: '确认卸载' }).click();
  await expect(page.getByRole('button', { name: '安装 语义视频剪辑' })).toBeVisible();
});

test('shows a skill dialog at 400px and prepares a trial without sending the draft', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 400, height: 740 });
  await page.goto('/');
  await page.getByRole('textbox', { name: '剪辑需求' }).fill('待处理素材');
  await page.getByRole('button', { name: '插件和技能', exact: true }).click();
  await page.getByRole('button', { name: '安装 语义视频剪辑' }).click();
  await page.getByRole('button', { name: '语义视频剪辑操作', exact: true }).click();
  const menu = page.getByRole('menu', { name: '语义视频剪辑操作' });
  await expect(menu).toBeVisible();
  const menuBounds = (await menu.boundingBox())!;
  expect(menuBounds.x).toBeGreaterThanOrEqual(0);
  expect(menuBounds.x + menuBounds.width).toBeLessThanOrEqual(400);
  await page.screenshot({ path: testInfo.outputPath('plugin-row-menu-narrow.png') });
  await menu.getByRole('menuitem', { name: '管理', exact: true }).click();
  await expect(page.getByRole('region', { name: '建议指令' })).toContainText('$short-drama-editing');
  await page.screenshot({ path: testInfo.outputPath('plugin-detail-narrow-installed.png') });
  await page.getByRole('button', { name: '查看 short-drama-editing' }).click();
  const dialog = page.getByRole('dialog', { name: '短剧剪辑技能详情' });
  await expect(dialog.getByLabel('技能正文')).toContainText('浏览器预览技能正文');
  await dialog.getByRole('button', { name: '技能操作' }).click();
  await expect(dialog.getByRole('menuitem', { name: '在文件资源管理器中显示' })).toBeVisible();
  const bounds = (await dialog.boundingBox())!;
  expect(bounds.x).toBeGreaterThanOrEqual(0);
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(400);
  expect(await dialog.evaluate(element => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(1);
  await page.screenshot({ path: testInfo.outputPath('skill-dialog-narrow.png') });
  await page.keyboard.press('Escape');
  await expect(dialog).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: '查看 short-drama-editing' }).click();
  await page.getByRole('dialog', { name: '短剧剪辑技能详情' }).getByRole('button', { name: '使用' }).click();
  await expect(page.getByRole('textbox', { name: '剪辑需求' })).toHaveValue('$short-drama-editing\n待处理素材');
});
